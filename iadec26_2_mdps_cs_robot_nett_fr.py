afficher_resultats("2. Batterie qui se décharge vite", q=0.9, c=0.5, pDust=0.1)

# 3. Batterie très fiable
afficher_resultats("3. Batterie très fiable", q=0.05, c=0.5, pDust=0.1)

# 4. Charge lente
