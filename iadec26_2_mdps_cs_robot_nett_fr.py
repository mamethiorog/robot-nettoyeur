# ============================================================
# QUESTION A : MODELISATION DU PROBLEME PAR UN MDP
# ============================================================
#
# On doit :
# - définir les états et les actions du robot
# - définir les probabilités de transition
# - fournir les matrices P et R
# - dessiner le MDP et justifier la modélisation
#
# P : matrices des probabilités de transition
# R : matrice des récompenses


# ------------------------------------------------------------
# A.1 - Définition des états et des actions
# ------------------------------------------------------------

states = 5
actions = 2

# Les 5 états du robot :
# LD : robot dans le salon, salon sale
# LC : robot dans le salon, salon propre
# CD : robot au chargeur, salon sale
# CC : robot au chargeur, salon propre
# O  : robot hors tension
STATES = ["LD", "LC", "CD", "CC", "O"]

# Les 2 actions :
# Action 0 : nettoyer
# Action 1 : charger
ACTIONS = ["nettoyer", "charger"]

# ------------------------------------------------------------
# A.2 - Définition des paramètres du MDP
# ------------------------------------------------------------

eps = 0.1       # Probabilité de ne pas réussir à nettoyer
gamma = 0.9     # Facteur d'actualisation

# e : probabilité de panne lorsque le robot nettoie
#     depuis le salon
#
# pDust : probabilité que le salon devienne sale
#         pendant l'action charger

# ============================================================
# QUESTION B : CHOIX DES RECOMPENSES
# ============================================================
#
# On doit proposer des valeurs intuitives et les justifier.
#
# rc : récompense lorsque le salon est propre
# rd : récompense lorsque le salon est sale
# costcrash : pénalité lorsque le robot est hors tension
#
# On doit respecter : costcrash <= rd < rc

rc = 5
rd = -1
costcrash = -10

# Justification :
# rc = 5 : on favorise un salon propre.
# rd = -1 : on pénalise légèrement un salon sale.
# costcrash = -10 : on pénalise fortement une panne.
#
# Les récompenses dépendent de l'état courant.
# Elles sont identiques pour les deux actions dans un même état.


# ============================================================
# QUESTION A (SUITE) : MATRICES DE TRANSITION ET RECOMPENSES
# ============================================================


# ------------------------------------------------------------
# A.3 - Construction des matrices P et R
# ------------------------------------------------------------
def create_mdp(e, eps, pDust, rc, rd, costcrash, e_charge=0):
    # P a pour dimensions: (actions, states, states)
    # e_charge: risque de panne en nettoyant depuis le chargeur (0 = sujet d'origine)
    P = np.array([

        # ----------------------------------------------------
        # ACTION 0 : NETTOYER
        # ----------------------------------------------------
        [
            [(1-e)*eps, (1-e)*(1-eps), 0, 0, e],
                  [0, (1-e), 0, 0, e],
                  [(1-e_charge)*eps, (1-e_charge)*(1-eps), 0, 0, e_charge],
                  [0, (1-e_charge), 0, 0, e_charge],
                  [0, 0, 0, 0, 1]],

                   # ----------------------------------------------------
                   # ACTION 1 : CHARGER
                   # ----------------------------------------------------

                  [[0, 0, 1, 0, 0],
                   [0, 0, pDust, (1-pDust), 0],
                   [0, 0, 1, 0, 0],
                   [0, 0, pDust, (1-pDust), 0],
                   [0, 0, 0, 0, 1]]])
    # --------------------------------------------------------
    # MATRICE R : RECOMPENSES
    # --------------------------------------------------------
    #
    # Dimensions: (states, actions)
    # Chaque ligne correspond à un état.
    # Chaque colonne correspond à une action.
    #
    # On utilise la récompense de l'état courant.
    R = np.array([
        [rd, rd],                  # LD : salon sale
        [rc, rc],                  # LC : salon propre
        [rd, rd],                  # CD : salon sale
        [rc, rc],                  # CC : salon propre
        [costcrash, costcrash]     # O : robot hors tension
    ])

    return(P,R)

# ------------------------------------------------------------
# A.4 - Affichage des matrices P et R
# ------------------------------------------------------------
#
# On choisit ici :
# e = 0.2 : probabilité de panne de 20 %
# pDust = 0.3 : probabilité de salissure de 30 %
#
# Ces valeurs permettent d'illustrer les matrices.

P, R = create_mdp(0.2, eps, 0.3, rc, rd, costcrash)

# Vérification des matrices du MDP
mdptoolbox.util.check(P, R)

print("Matrice Nettoyer :")
print(P[0])

print("Matrice Charger :")
print(P[1])

print("Matrice R :")
print(R)

# ============================================================
# QUESTION C : RECHERCHE DE LA POLITIQUE OPTIMALE
# ============================================================
#
# On utilise l'algorithme Value Iteration.
#
# On doit étudier quatre situations :
# 1. Risque de panne élevé
# 2. Risque de panne faible
# 3. Très bonne batterie
# 4. Salon qui se salit rapidement
#
# On doit interpréter les politiques obtenues.

# ------------------------------------------------------------
# C.1 - Fonction de résolution du MDP
# ------------------------------------------------------------

def solve(e, pDust, e_charge=0, costcrash=costcrash, gamma=gamma):
    # Construire les matrices pour les paramètres choisis
    P, R = create_mdp(e, eps, pDust, rc, rd, costcrash, e_charge)
    mdptoolbox.util.check(P, R)
    vi = mdptoolbox.mdp.ValueIteration(P, R, gamma, epsilon=1e-6)
    vi.run()
     # Retourner la politique optimale et les valeurs des états
    return vi.policy, vi.V, vi.iter

# ------------------------------------------------------------
# C.2 - Premier test de Value Iteration
# ------------------------------------------------------------

# Test avec e = 0.2 et pDust = 0.3
policy, V , iter= solve(0.2, 0.3)

print("Politique optimale :", policy)
print("Valeurs des états :", V)
print("Nombre d'itérations :", iter)

# ------------------------------------------------------------
# C.3 - Comparaison des quatre situations demandées
# ------------------------------------------------------------

cases = [("e eleve", 0.7, 0.1),
         ("e faible", 0.2, 0.1),
         ("tres bonne batterie", 0.001, 0.1),
         ("salon se salit vite", 0.001, 0.9)]

# Pour chaque scénario :
# - construire le MDP
# - calculer la politique optimale
# - afficher les actions optimales
# - afficher les valeurs des états

for name, e, pDust in cases:
    policy, V, iter = solve(e, pDust)

    print(f"\n{name:22s} e={e:<6} pDust={pDust:<4}")

    # Afficher la meilleure action dans chaque état,
    # sauf O, où les deux actions sont équivalentes.
    print({
        s: ACTIONS[a]
        for s, a in zip(STATES[:4], policy)
    })

    # Afficher les valeurs des cinq états
    print("Valeurs :", np.round(V, 2))

