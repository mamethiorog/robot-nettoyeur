# ANALYSE SUPPLEMENTAIRE : SEUIL DE PROBABILITE DE PANNE
# ============================================================
#
# Objectif :
# rechercher une valeur seuil de e à partir de laquelle
# le robot préfère Charger plutôt que Nettoyer.
#
# On utilise une recherche par dichotomie.
#
# Cette étude n'est pas explicitement demandée dans le TP.


# ------------------------------------------------------------
# Variante 2 - Recherche du seuil de e
# ------------------------------------------------------------

def seuil_e(state, e_max=0.3, **kw):
    # Si Nettoyer reste optimal pour e = e_max,
    # aucun seuil n'est trouvé dans l'intervalle testé.

    if solve(e_max, pDust_fixed, **kw)[0][state] == 0:
        return np.nan  # nettoyer meme pour e = e_max
    lo, hi = 0.0, e_max
    for _ in range(25):
        mid = (lo + hi) / 2
        if solve(mid, pDust_fixed, **kw)[0][state] == 0:
            lo = mid
        else:
            hi = mid
    return hi

# ------------------------------------------------------------
# Variante 3 - Influence de costcrash et gamma
