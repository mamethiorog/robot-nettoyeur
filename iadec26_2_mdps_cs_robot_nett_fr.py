ax2.set_xlabel("gamma")
ax2.set_ylabel("seuil de e (echelle log)")
ax2.grid(alpha=0.3, which="both")
ax2.legend()

fig3.tight_layout()
fig3.savefig("seuil_costcrash_gamma.png", dpi=120)
