# balayage de e et pDust

# ------------------------------------------------------------
# C.5 - Balayage des paramètres e et pDust
# ------------------------------------------------------------
#
# On teste plusieurs valeurs de e et pDust.
#
# Objectif :
# voir pour quelles valeurs le robot choisit
# Nettoyer ou Charger dans les états LD et LC.

e_values = np.linspace(0, 0.3, 61)
pDust_values = np.linspace(0, 1, 51)

def policy_map(e_charge=0):

    # grid[0] : politique optimale dans l'état LD
    # grid[1] : politique optimale dans l'état LC

    grid = np.zeros(
        (2, len(pDust_values), len(e_values)),
        dtype=int
    )

    for i, pDust in enumerate(pDust_values):
        for j, e in enumerate(e_values):

            policy, _, _ = solve(e, pDust, e_charge)

            grid[0, i, j], grid[1, i, j] = policy[0], policy[1]

    return grid

grid = policy_map()

# ------------------------------------------------------------
# C.6 - Valeurs des états en fonction de e
# ------------------------------------------------------------
#
# On fixe pDust = 0.1.
# On fait varier la probabilité de panne e.
#
# Objectif :
